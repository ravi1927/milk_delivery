function page(title, subtitle, body) {
  const generated = new Date().toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short' });
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><style>${CSS}</style></head><body>
  <div class="head">
    <div class="brand"><img src="${LOGO_DATA_URI}" alt="logo"/><div><h1>${esc(BUSINESS.name)}</h1><p>${esc(BUSINESS.tagline)}</p></div></div>
    <div class="doc"><h2>${esc(title)}</h2><p>${esc(subtitle)}</p><p>Generated ${esc(generated)}</p></div>
  </div>
  ${body}
  <div class="foot">${esc(BUSINESS.name)} • Generated by the delivery management app</div>
  </body></html>`;
}

const card = (value, label) => `<div class="card"><b>${esc(value)}</b><span>${esc(label)}</span></div>`;
const table = (heads, rows, total) => `<table><thead><tr>${heads.map(([h, cls]) => `<th class="${cls || ''}">${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.join('')}${total || ''}</tbody></table>`;
const tr = (cells) => `<tr>${cells.map(([v, cls]) => `<td class="${cls || ''}">${esc(v)}</td>`).join('')}</tr>`;
const pct = (a, b) => (b ? `${Math.round((a / b) * 100)}%` : '0%');

// ───────────────────────── Delivery report (one day or a range) ─────────────────────────
export function summarizeDeliveries({ deliveries, customers, users, areas, from, to }) {
  const rows = deliveries.filter((d) => d.date >= from && d.date <= to).sort((a, b) => a.date.localeCompare(b.date));
  const cName = (id) => customers.find((c) => c.id === id)?.name || 'Customer';
  const uName = (id) => users.find((u) => u.id === id)?.name || 'Unassigned';
  const aName = (id) => areas.find((a) => a.id === id)?.name || '—';
  const delivered = rows.filter((r) => r.status === 'delivered');
  const group = (keyFn, nameFn) => {
    const m = new Map();
    for (const r of rows) {
      const k = keyFn(r) ?? '_none';
      const g = m.get(k) || { name: nameFn(keyFn(r)), total: 0, done: 0, litres: 0, amount: 0 };
      g.total += 1;
      if (r.status === 'delivered') { g.done += 1; g.litres += Number(r.expectedLitres || 0); g.amount += Number(r.amount || 0); }
      m.set(k, g);
    }
    return [...m.values()].sort((a, b) => a.name.localeCompare(b.name));
  };
  const byDay = new Map();
  for (const r of rows) {
    const g = byDay.get(r.date) || { date: r.date, total: 0, done: 0, litres: 0, amount: 0 };
    g.total += 1;
    if (r.status === 'delivered') { g.done += 1; g.litres += Number(r.expectedLitres || 0); g.amount += Number(r.amount || 0); }
    byDay.set(r.date, g);
  }
  return {
    rows, cName, uName, aName,
    totals: {
      records: rows.length, delivered: delivered.length, pending: rows.length - delivered.length,
      litres: round2(delivered.reduce((n, r) => n + Number(r.expectedLitres || 0), 0)),
      amount: round2(delivered.reduce((n, r) => n + Number(r.amount || 0), 0)),
      expectedAmount: round2(rows.reduce((n, r) => n + Number(r.amount || 0), 0)),
    },
    byBoy: group((r) => r.boyId, (id) => (id ? uName(id) : 'Unassigned')),
    byArea: group((r) => r.areaId, aName),
    byCustomer: group((r) => r.customerId, cName),
    byDay: [...byDay.values()],
  };
}

export function deliveryReportHtml(data) {
  const { from, to } = data;
  const S = summarizeDeliveries(data);
  const t = S.totals;
  const single = from === to;
  const subtitle = single ? niceDate(from) : `${niceDate(from)} – ${niceDate(to)}`;
  const perfRows = (list) => list.map((g) => tr([[g.name], [g.total, 'r'], [g.done, 'r'], [g.total - g.done, 'r'], [fmtLitres(g.litres), 'r'], [fmtAmount(g.amount), 'r'], [pct(g.done, g.total), 'r']]));
  const perfHead = (first) => [[first], ['Records', 'r'], ['Delivered', 'r'], ['Pending', 'r'], ['Litres', 'r'], ['Amount', 'r'], ['Done', 'r']];

  let body = `<div class="cards">${card(t.records, 'Delivery records')}${card(t.delivered, 'Delivered')}${card(t.pending, 'Pending')}${card(pct(t.delivered, t.records), 'Completion')}${card(fmtLitres(t.litres), 'Litres delivered')}${card(fmtAmount(t.amount), 'Delivered amount')}</div>`;
  if (!single) body += `<h3>Day-wise summary</h3>${table([['Date'], ['Records', 'r'], ['Delivered', 'r'], ['Pending', 'r'], ['Litres', 'r'], ['Amount', 'r']], S.byDay.map((g) => tr([[g.date], [g.total, 'r'], [g.done, 'r'], [g.total - g.done, 'r'], [fmtLitres(g.litres), 'r'], [fmtAmount(g.amount), 'r']])))}`;
  body += `<h3>Delivery boy report</h3>${table(perfHead('Delivery boy'), perfRows(S.byBoy))}`;
  body += `<h3>Area report</h3>${table(perfHead('Area'), perfRows(S.byArea))}`;
  body += `<h3>Customer-wise report</h3>${table(perfHead('Customer'), perfRows(S.byCustomer))}`;
  body += `<h3>Delivery details</h3>${table(
    [['Date'], ['Customer'], ['Area'], ['Delivery boy'], ['Litres', 'r'], ['Amount', 'r'], ['Status'], ['Time']],
    S.rows.map((r) => tr([[r.date], [S.cName(r.customerId)], [S.aName(r.areaId)], [S.uName(r.boyId)], [fmtLitres(r.expectedLitres || 0), 'r'], [fmtAmount(r.amount || 0), 'r'], [r.status === 'delivered' ? 'Delivered' : 'Pending', r.status === 'delivered' ? 'ok' : 'warn'], [r.deliveredAt ? new Date(r.deliveredAt).toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit' }) : '—']])),
  )}`;
  if (!S.rows.length) body += '<p class="note">No delivery records were found for this period.</p>';
  return page(single ? 'Daily Delivery Report' : 'Delivery Report', subtitle, body);
}

// ───────────────────────── Billing summary ─────────────────────────
const waText = (b) => ({ pending: 'Not sent', opened: 'Opened, not confirmed', sent: 'Sent', delivered: 'Delivered', read: 'Read', failed: 'Failed' }[b.wa?.status || 'pending']);

export function billsReportHtml({ title = 'Billing Summary', subtitle = '', bills }) {
  const sorted = [...bills].sort((a, b) => a.customerName.localeCompare(b.customerName) || a.periodStart.localeCompare(b.periodStart));
  const total = round2(sorted.reduce((n, b) => n + Number(b.amount || 0), 0));
  const litres = round2(sorted.reduce((n, b) => n + Number(b.litres || 0), 0));
  const ok = sorted.filter((b) => SENT_STATES.includes(b.wa?.status));
  const problems = sorted.filter((b) => !SENT_STATES.includes(b.wa?.status));
  let body = `<div class="cards">${card(sorted.length, 'Bills')}${card(fmtLitres(litres), 'Total litres')}${card(fmtAmount(total), 'Total amount')}${card(ok.length, 'Messages sent')}${card(problems.length, 'Not sent / failed')}</div>`;
  body += `<h3>Customer bills</h3>${table(
    [['Customer'], ['Mobile'], ['Period'], ['Days', 'r'], ['Litres', 'r'], ['Rate', 'r'], ['Amount', 'r'], ['WhatsApp']],
    sorted.map((b) => tr([[b.customerName], [b.phone ? `+${b.phone}` : 'Missing'], [`${b.periodStart} to ${b.periodEnd}`], [b.days, 'r'], [fmtLitres(b.litres), 'r'], [fmtAmount(b.ratePerLitre), 'r'], [fmtAmount(b.amount), 'r'], [waText(b), SENT_STATES.includes(b.wa?.status) ? 'ok' : 'bad']])),
    `<tr class="total"><td colspan="4">Total</td><td class="r">${esc(fmtLitres(litres))}</td><td></td><td class="r">${esc(fmtAmount(total))}</td><td></td></tr>`,
  )}`;
  if (problems.length) {
    body += `<h3>Messages not delivered – action needed</h3>${table(
      [['Customer'], ['Mobile'], ['Amount', 'r'], ['Reason']],
      problems.map((b) => tr([[b.customerName], [b.phone ? `+${b.phone}` : 'Missing'], [fmtAmount(b.amount), 'r'], [messageProblem(b), 'bad']])),
    )}`;
  }
  return page(title, subtitle, body);
}

// ───────────────────────── Single customer bill ─────────────────────────
export function invoiceHtml(bill) {
  const line = (k, v) => `<div class="row"><span>${esc(k)}</span><b>${esc(v)}</b></div>`;
  const body = `<div class="box">
    ${line('Customer', bill.customerName)}
    ${line('Mobile', bill.phone ? `+${bill.phone}` : '—')}
    ${line('Billing period', `${niceDate(bill.periodStart)} to ${niceDate(bill.periodEnd)}`)}
    ${line('Daily milk', bill.milkQuantity)}
    ${line('Days billed', `${bill.days}${bill.basis === 'delivered' ? ' (delivered days only)' : ''}`)}
    ${line('Total litres', fmtLitres(bill.litres))}
    ${line('Rate per litre', fmtAmount(bill.ratePerLitre))}
    <div class="row" style="border:none"><span>Total amount to pay</span><span class="big">${esc(fmtAmount(bill.amount))}</span></div>
  </div>
  ${BUSINESS.paymentNote ? `<p class="note">${esc(BUSINESS.paymentNote)}</p>` : ''}
  <p class="note">Thank you for choosing ${esc(BUSINESS.name)}.</p>`;
  return page('Milk Bill', `${niceDate(bill.periodStart)} – ${niceDate(bill.periodEnd)}`, body);
}
